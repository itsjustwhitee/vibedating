export const detectLang = () => (globalThis.navigator?.language?.startsWith('it') ? 'it' : 'en');

const LANG_KEY = 'vibedating:lang';
export function savedLang() {
  try {
    const v = localStorage.getItem(LANG_KEY);
    return v === 'it' || v === 'en' ? v : null;
  } catch {
    return null;
  }
}
export function saveLang(lang) {
  try { localStorage.setItem(LANG_KEY, lang); } catch { /* storage unavailable */ }
}

export function strings(lang, table = STRINGS) {
  const s = table[lang === 'en' ? 'en' : 'it'];
  const t = (key, vars = {}) => String(s[key] ?? key).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
  return { s, t };
}
